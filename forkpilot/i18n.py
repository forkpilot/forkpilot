"""Message catalogue: every user-facing string, one dict per language.

English is the default. The language comes from `set_lang` (the CLI's --lang) or the FP_LANG
environment variable. A key missing in the chosen language falls back to English. Strings that
the program reads back (event keys, record fields) never go through here; only display text does.
"""
from __future__ import annotations

import os

LANGS = ("en", "tr")
DEFAULT = "en"
_lang: str | None = None


def set_lang(code: str) -> None:
    if code not in LANGS:
        raise ValueError(f"unknown language {code!r}; choose from {', '.join(LANGS)}")
    global _lang
    _lang = code
    os.environ["FP_LANG"] = code      # worker processes and child commands inherit the choice


def lang(explicit: str | None = None) -> str:
    code = explicit or _lang or os.environ.get("FP_LANG") or DEFAULT
    return code if code in LANGS else DEFAULT


def t(key: str, lang_: str | None = None, **kw) -> str:
    code = lang(lang_)
    text = MSG[code].get(key) or MSG[DEFAULT][key]
    return text.format(**kw) if kw else text


